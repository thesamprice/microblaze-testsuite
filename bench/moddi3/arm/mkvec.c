/* Host side: turn ../gen.c's vectors.h into the compact arrays bench.c
   needs for one routine, to fit the micro:bit's 256 KB of flash.

     mkvec OP > cvec.h     (OP as in bench.c)

   Compile with -I pointing at the directory holding the vectors.h to
   use: gen's output for the signed vectors, "gen unsigned"'s for the
   unsigned ones.  */

#include <stdio.h>
#include <stdlib.h>
#include "vectors.h"

int
main (int argc, char **argv)
{
  int op = atoi (argv[1]);
  printf ("/* Generated by mkvec %d.  Do not edit.  */\n", op);
  printf ("#define NTV %d\n#define NCLASS %d\n", NTV, NCLASS);
  printf ("static const unsigned long long va[NTV] = {\n");
  for (int i = 0; i < NTV; i++)
    printf ("%lluULL,\n", (unsigned long long) tv[i].a);
  printf ("};\nstatic const unsigned long long vb[NTV] = {\n");
  for (int i = 0; i < NTV; i++)
    printf ("%lluULL,\n", (unsigned long long) tv[i].b);
  /* The wanted results: quotient, then remainder for the divmods.  */
  printf ("};\nstatic const unsigned long long vw[NTV] = {\n");
  for (int i = 0; i < NTV; i++)
    {
      unsigned long long w;
      switch (op)
	{
	case 0: w = tv[i].r; break;
	case 1: w = tv[i].ur; break;
	case 2: case 4: w = tv[i].q; break;
	default: w = tv[i].uq; break;
	}
      printf ("%lluULL,\n", w);
    }
  printf ("};\n");
  if (op >= 4)
    {
      printf ("static const unsigned long long vr[NTV] = {\n");
      for (int i = 0; i < NTV; i++)
	printf ("%lluULL,\n", op == 4 ? (unsigned long long) tv[i].r
		: tv[i].ur);
      printf ("};\n");
    }
  /* The classes, for summary.py: one per line on stderr.  */
  for (int i = 0; i < NTV; i++)
    fprintf (stderr, "%s\n", class_name[tv[i].cls]);
  return 0;
}
