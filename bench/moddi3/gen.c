/* Host side: write the test vectors for __moddi3, __umoddi3, __divdi3
   and __udivdi3, with the results computed by the host, as a header for
   bench.c.  The unsigned results use the same bit patterns, so negative
   operands become values with the top bit set.

   The generator is a fixed splitmix64 rather than rand(), so the vectors,
   and hence the instruction counts, are the same whatever the host's libc.

   The vectors come in classes, because the cost of the routines under test
   depends on the operand widths in different ways: the shift-and-subtract
   loop of the hand-written version runs once per quotient bit, while the
   generic C takes a different path when the divisor fits in 32 bits.  */

#include <stdio.h>
#include <stdint.h>
#include <limits.h>

static uint64_t state = 20261107;

static uint64_t
next (void)
{
  uint64_t z = (state += 0x9e3779b97f4a7c15ULL);
  z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
  z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
  return z ^ (z >> 31);
}

/* A random value with exactly BITS significant bits, 1 <= BITS <= 63,
   negated half the time.  */
static long long
rnd (int bits)
{
  uint64_t x = (next () & ((1ULL << bits) - 1)) | (1ULL << (bits - 1));
  long long v = (long long) x;
  return (next () & 1) ? -v : v;
}

static void
pv (long long x)
{
  /* LLONG_MIN has no literal form.  */
  if (x == LLONG_MIN)
    printf ("(-9223372036854775807LL - 1)");
  else
    printf ("%lldLL", x);
}

static int count[8];

static void
emit (int cls, long long a, long long b)
{
  if (b == 0 || (a == LLONG_MIN && b == -1))
    return;					/* undefined */
  printf ("  { ");
  pv (a);
  printf (", ");
  pv (b);
  printf (", ");
  pv (a / b);
  printf (", ");
  pv (a % b);
  printf (", %lluULL, %lluULL, %d },\n",
	  (unsigned long long) a / (unsigned long long) b,
	  (unsigned long long) a % (unsigned long long) b, cls);
  count[cls]++;
}

static const char *const names[] = {
  "edge", "small", "wide/narrow", "wide/wide", "mixed"
};
#define NCLASS 5

int
main (void)
{
  static const long long v[] = {
    0, 1, -1, 2, -2, 3, -3, 7, -7, 10, -10, 100, -100,
    0x7fffffff, -0x7fffffff, 0x80000000LL, -0x80000000LL,
    0x100000000LL, -0x100000000LL, 0x123456789abcLL, -0x123456789abcLL,
    LLONG_MAX, LLONG_MIN, LLONG_MAX - 1, LLONG_MIN + 1,
    0x5555555555555555LL, -0x5555555555555555LL
  };
  int n = sizeof v / sizeof v[0];

  printf ("/* Generated by gen.c.  Do not edit.  */\n");
  printf ("struct tv { long long a, b, q, r; unsigned long long uq, ur; int cls; };\n");
  printf ("static const struct tv tv[] = {\n");

  /* 0: every pair of the boundary values.  */
  for (int i = 0; i < n; i++)
    for (int j = 0; j < n; j++)
      emit (0, v[i], v[j]);

  for (int k = 0; k < 1000; k++)
    {
      int ba = 1 + (int) (next () % 31), bb = 1 + (int) (next () % 31);
      /* 1: both operands fit in 32 bits.  */
      emit (1, rnd (ba), rnd (bb));
      /* 2: a 63-bit dividend, a divisor of at most 31 bits.  */
      emit (2, rnd (63), rnd (bb));
      /* 3: both 63 bits, so the quotient is small.  */
      emit (3, rnd (63), rnd (63));
      /* 4: dividend of 33 to 63 bits, divisor of 1 to 63 bits.  */
      emit (4, rnd (33 + (int) (next () % 31)), rnd (1 + (int) (next () % 63)));
    }

  int total = 0;
  for (int c = 0; c < NCLASS; c++)
    total += count[c];
  printf ("};\n#define NTV %d\n#define NCLASS %d\n", total, NCLASS);
  printf ("static const char *const class_name[NCLASS] = {");
  for (int c = 0; c < NCLASS; c++)
    printf ("%s\"%s\"", c ? ", " : " ", names[c]);
  printf (" };\n");
  fprintf (stderr, "%d vectors\n", total);
  return 0;
}
